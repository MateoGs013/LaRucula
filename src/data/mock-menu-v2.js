/** Helper: get all category summaries */
export function getMenuCategories() {
  return mockMenuFull.categories.map(({ id, slug, name, short_description, icon, order }) => ({
    id, slug, name, short_description, icon, order,
  }));
}

/** Helper: get a single category by slug */
export function getMenuCategory(slug) {
  return mockMenuFull.categories.find((c) => c.slug === slug) || null;
}

/** Helper: get featured items across all categories */
export function getFeaturedItems() {
  const allItems = mockMenuFull.categories.flatMap((c) => c.items);
  return mockMenuFull.featured
    .map((slug) => allItems.find((item) => item.slug === slug))
    .filter(Boolean);
}
